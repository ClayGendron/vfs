"""Probe 06: four spellings of "the newest deleted row at each of these paths", as whole statements.

Probe 03 counted the inner select alone. This probe counts the statement a storage would issue, with the
row fetched, on a table of 1,000,000 live rows, 40,000 paths with one deleted row each, and one path with
10,000 deleted rows. Each spelling is run for 3 targets, 1,000 targets and 32,000 targets, the last near
one chunk of the parameter budget. On SQLite the count is virtual-machine steps. On Postgres it is the
buffers the plan touched and whether any node read the table by a sequential scan. Nothing is timed.
"""

from __future__ import annotations

import asyncio
import json
import sqlite3
import sys
from pathlib import Path as FsPath

import asyncpg

sys.path.insert(0, str(FsPath(__file__).parent))

from harness import POSTGRES_URL

TOP = (
    "SELECT n.{what} FROM t n WHERE n.path = targets.p AND n.deleted_at IS NOT NULL"
    " ORDER BY n.deleted_at DESC, n.name_generation DESC LIMIT 1"
)
SPELLINGS = {
    "in: the row's id among the targets' newest ids": (
        "WITH targets(p) AS (VALUES {rows}) SELECT e.id, e.path, e.deleted_at FROM t e"
        " WHERE e.id IN (SELECT (" + TOP.format(what="id") + ") FROM targets)"
    ),
    "join: each target joined to the row its newest id names": (
        "WITH targets(p) AS (VALUES {rows}) SELECT e.id, e.path, e.deleted_at FROM targets"
        " JOIN t e ON e.id = (" + TOP.format(what="id") + ")"
    ),
    "staged: the newest ids gathered first, then joined": (
        "WITH targets(p) AS (VALUES {rows}), newest(id) AS MATERIALIZED (SELECT (" + TOP.format(what="id") + ") FROM targets)"
        " SELECT e.id, e.path, e.deleted_at FROM newest JOIN t e ON e.id = newest.id"
    ),
    "lateral: each target reads its own newest row": (
        "WITH targets(p) AS (VALUES {rows}) SELECT e.id, e.path, e.deleted_at FROM targets"
        " CROSS JOIN LATERAL (" + TOP.format(what="*") + ") e"
    ),
}
SIZES = (3, 1_000, 32_000)


def targets(count: int) -> list[str]:
    return ["/churn"] + [f"/gone/f{i:06d}" for i in range(1, count)]


def on_sqlite() -> None:
    conn = sqlite3.connect(":memory:")
    print("== SQLite", sqlite3.sqlite_version)
    conn.executescript(
        """
        CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, parent_id TEXT, path TEXT NOT NULL, name TEXT NOT NULL,
          deleted_at BIGINT, name_generation BIGINT NOT NULL DEFAULT 0, body TEXT,
          UNIQUE (path, name_generation), UNIQUE (parent_id, name_generation, name));
        CREATE INDEX t_trashed_path ON t (path, deleted_at, name_generation) WHERE deleted_at IS NOT NULL;
        WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 1000000)
          INSERT INTO t (parent_id, path, name, body) SELECT 'live', printf('/live/f%07d', i), printf('f%07d', i), 'x' FROM n;
        WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 40000)
          INSERT INTO t (parent_id, path, name, deleted_at, name_generation, body)
          SELECT 'gone', printf('/gone/f%06d', i), printf('f%06d', i), i, 2000000 + i, 'x' FROM n;
        WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 10000)
          INSERT INTO t (parent_id, path, name, deleted_at, name_generation, body)
          SELECT 'root', '/churn', 'churn', 100000 + i, 3000000 + i, 'x' FROM n;
        ANALYZE;
        """
    )
    steps = [0]

    def tick() -> int:
        steps[0] += 1
        return 0

    for label, spelling in SPELLINGS.items():
        if label.startswith("lateral"):
            print(f"    {label}: not run, SQLite has no LATERAL")
            continue
        for count in SIZES:
            sql = spelling.format(rows=", ".join("(?)" for _ in range(count)))
            steps[0] = 0
            conn.set_progress_handler(tick, 1)
            found = conn.execute(sql, targets(count)).fetchall()
            conn.set_progress_handler(None, 1)
            print(f"    {label}: {count} targets, {len(found)} rows, vm_steps={steps[0]}, a target={steps[0] / count:.1f}")
    conn.close()


def nodes(plan: dict) -> list[dict]:
    out = [plan]
    for child in plan.get("Plans", []):
        out += nodes(child)
    return out


async def on_postgres() -> None:
    if not POSTGRES_URL:
        print("VFS_PROBE_POSTGRES_URL is unset: the Postgres leg is skipped")
        return
    conn = await asyncpg.connect(POSTGRES_URL.replace("+asyncpg", ""))
    print("== Postgres", (await conn.fetchval("SHOW server_version")).split()[0])
    await conn.execute("DROP TABLE IF EXISTS t")
    await conn.execute(
        "CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, parent_id TEXT, path TEXT NOT NULL,"
        " name TEXT NOT NULL, deleted_at BIGINT, name_generation BIGINT NOT NULL DEFAULT 0, body TEXT,"
        " UNIQUE (path, name_generation), UNIQUE (parent_id, name_generation, name))"
    )
    await conn.execute("CREATE INDEX t_trashed_path ON t (path, deleted_at, name_generation) WHERE deleted_at IS NOT NULL")
    await conn.execute(
        "INSERT INTO t (parent_id, path, name, body) SELECT 'live', '/live/f' || lpad(i::text, 7, '0'),"
        " 'f' || lpad(i::text, 7, '0'), 'x' FROM generate_series(1, 1000000) i"
    )
    await conn.execute(
        "INSERT INTO t (parent_id, path, name, deleted_at, name_generation, body) SELECT 'gone',"
        " '/gone/f' || lpad(i::text, 6, '0'), 'f' || lpad(i::text, 6, '0'), i, 2000000 + i, 'x' FROM generate_series(1, 40000) i"
    )
    await conn.execute(
        "INSERT INTO t (parent_id, path, name, deleted_at, name_generation, body)"
        " SELECT 'root', '/churn', 'churn', 100000 + i, 3000000 + i, 'x' FROM generate_series(1, 10000) i"
    )
    await conn.execute("VACUUM ANALYZE t")
    await conn.execute("SET statement_timeout = '60s'")
    for label, spelling in SPELLINGS.items():
        for count in SIZES:
            sql = spelling.format(rows=", ".join(f"(${i}::text)" for i in range(1, count + 1)))
            try:
                raw = await conn.fetchval("EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) " + sql, *targets(count))
            except asyncpg.PostgresError as exc:
                print(f"    {label}: {count} targets, refused: {type(exc).__name__}")
                continue
            plan = json.loads(raw)[0]["Plan"]
            scans = [n for n in nodes(plan) if n["Node Type"] == "Seq Scan" and n.get("Relation Name") == "t"]
            buffers = plan["Shared Hit Blocks"] + plan["Shared Read Blocks"]
            print(
                f"    {label}: {count} targets, {plan['Actual Rows']} rows, buffers={buffers},"
                f" a target={buffers / count:.1f}, sequential scans of the table={len(scans)}"
            )
    await conn.execute("DROP TABLE t")
    await conn.close()


on_sqlite()
asyncio.run(on_postgres())
