"""Probe 07: the newest deleted row at a path that one caller owns, with and without an index that leads to it.

The table is probe 06's with an owner on each row. One path holds 10,000 deleted rows owned by another caller
above one older row the asking caller owns. The lookup is driven by its targets, as in probe 06, with the
owner as a term of the inner select. It is run first with the index on ``(path, deleted_at, name_generation)``
alone, then with a second partial index on ``(path, owner_id, deleted_at, name_generation)``. Nothing is timed.
"""

from __future__ import annotations

import asyncio
import json
import sqlite3
import sys
from pathlib import Path as FsPath

import asyncpg

sys.path.insert(0, str(FsPath(__file__).parent))

from harness import POSTGRES_URL

TOP = (
    "SELECT n.{what} FROM t n WHERE n.path = targets.p AND n.owner_id = {caller} AND n.deleted_at IS NOT NULL"
    " ORDER BY n.deleted_at DESC, n.name_generation DESC LIMIT 1"
)
SCALAR_JOIN = (
    "WITH targets(p) AS (VALUES {rows}) SELECT e.id, e.path, e.owner_id FROM targets JOIN t e ON e.id = (" + TOP + ")"
)
LATERAL = "WITH targets(p) AS (VALUES {rows}) SELECT e.id, e.path, e.owner_id FROM targets CROSS JOIN LATERAL (" + TOP + ") e"
OWNER_INDEX = "CREATE INDEX t_trashed_owner_path ON t (path, owner_id, deleted_at, name_generation) WHERE deleted_at IS NOT NULL"
SIZES = (3, 1_000, 32_000)


def targets(count: int) -> list[str]:
    return ["/churn"] + [f"/gone/f{i:06d}" for i in range(1, count)]


def on_sqlite() -> None:
    conn = sqlite3.connect(":memory:")
    print("== SQLite", sqlite3.sqlite_version)
    conn.executescript(
        """
        CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, parent_id TEXT, path TEXT NOT NULL, name TEXT NOT NULL,
          owner_id TEXT, deleted_at BIGINT, name_generation BIGINT NOT NULL DEFAULT 0, body TEXT,
          UNIQUE (path, name_generation), UNIQUE (parent_id, name_generation, name));
        CREATE INDEX t_trashed_path ON t (path, deleted_at, name_generation) WHERE deleted_at IS NOT NULL;
        WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 1000000)
          INSERT INTO t (parent_id, path, name, owner_id, body)
          SELECT 'live', printf('/live/f%07d', i), printf('f%07d', i), 'alice', 'x' FROM n;
        WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 40000)
          INSERT INTO t (parent_id, path, name, owner_id, deleted_at, name_generation, body)
          SELECT 'gone', printf('/gone/f%06d', i), printf('f%06d', i), 'alice', i, 2000000 + i, 'x' FROM n;
        WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 10001)
          INSERT INTO t (parent_id, path, name, owner_id, deleted_at, name_generation, body)
          SELECT 'root', '/churn', 'churn', CASE WHEN i = 1 THEN 'alice' ELSE 'bob' END, 100000 + i, 3000000 + i, 'x' FROM n;
        ANALYZE;
        """
    )
    steps = [0]

    def tick() -> int:
        steps[0] += 1
        return 0

    for label in ("with the path index alone", "with the owner index beside it"):
        if label.startswith("with the owner"):
            conn.execute(OWNER_INDEX)
            conn.execute("ANALYZE")
        for count in SIZES:
            sql = SCALAR_JOIN.format(rows=", ".join("(?)" for _ in range(count)), what="id", caller="?")
            steps[0] = 0
            conn.set_progress_handler(tick, 1)
            found = conn.execute(sql, [*targets(count), "alice"]).fetchall()
            conn.set_progress_handler(None, 1)
            print(f"    {label}: {count} targets, {len(found)} rows, vm_steps={steps[0]}, a target={steps[0] / count:.1f}")
    conn.close()


def nodes(plan: dict) -> list[dict]:
    out = [plan]
    for child in plan.get("Plans", []):
        out += nodes(child)
    return out


async def on_postgres() -> None:
    if not POSTGRES_URL:
        print("VFS_PROBE_POSTGRES_URL is unset: the Postgres leg is skipped")
        return
    conn = await asyncpg.connect(POSTGRES_URL.replace("+asyncpg", ""))
    print("== Postgres", (await conn.fetchval("SHOW server_version")).split()[0])
    await conn.execute("DROP TABLE IF EXISTS t")
    await conn.execute(
        "CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, parent_id TEXT, path TEXT NOT NULL,"
        " name TEXT NOT NULL, owner_id TEXT, deleted_at BIGINT, name_generation BIGINT NOT NULL DEFAULT 0, body TEXT,"
        " UNIQUE (path, name_generation), UNIQUE (parent_id, name_generation, name))"
    )
    await conn.execute("CREATE INDEX t_trashed_path ON t (path, deleted_at, name_generation) WHERE deleted_at IS NOT NULL")
    await conn.execute(
        "INSERT INTO t (parent_id, path, name, owner_id, body) SELECT 'live', '/live/f' || lpad(i::text, 7, '0'),"
        " 'f' || lpad(i::text, 7, '0'), 'alice', 'x' FROM generate_series(1, 1000000) i"
    )
    await conn.execute(
        "INSERT INTO t (parent_id, path, name, owner_id, deleted_at, name_generation, body) SELECT 'gone',"
        " '/gone/f' || lpad(i::text, 6, '0'), 'f' || lpad(i::text, 6, '0'), 'alice', i, 2000000 + i, 'x'"
        " FROM generate_series(1, 40000) i"
    )
    await conn.execute(
        "INSERT INTO t (parent_id, path, name, owner_id, deleted_at, name_generation, body) SELECT 'root', '/churn', 'churn',"
        " CASE WHEN i = 1 THEN 'alice' ELSE 'bob' END, 100000 + i, 3000000 + i, 'x' FROM generate_series(1, 10001) i"
    )
    await conn.execute("VACUUM ANALYZE t")
    await conn.execute("SET statement_timeout = '60s'")
    for label in ("with the path index alone", "with the owner index beside it"):
        if label.startswith("with the owner"):
            await conn.execute(OWNER_INDEX)
            await conn.execute("VACUUM ANALYZE t")
        for count in SIZES:
            rows = ", ".join(f"(${i}::text)" for i in range(1, count + 1))
            sql = LATERAL.format(rows=rows, what="*", caller=f"${count + 1}::text")
            raw = await conn.fetchval("EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) " + sql, *targets(count), "alice")
            plan = json.loads(raw)[0]["Plan"]
            scans = [n for n in nodes(plan) if n["Node Type"] == "Seq Scan" and n.get("Relation Name") == "t"]
            buffers = plan["Shared Hit Blocks"] + plan["Shared Read Blocks"]
            print(
                f"    {label}: {count} targets, {plan['Actual Rows']} rows, buffers={buffers},"
                f" a target={buffers / count:.1f}, sequential scans of the table={len(scans)}"
            )
    await conn.execute("DROP TABLE t")
    await conn.close()


on_sqlite()
asyncio.run(on_postgres())
