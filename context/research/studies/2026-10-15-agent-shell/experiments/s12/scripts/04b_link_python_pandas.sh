#!/bin/bash
# Stretch: relink python.wasm with numpy AND pandas as builtins; the inittab is generated from both build trees.
set -euo pipefail
HERE=$(CDPATH= cd "$(dirname "$0")/.." && pwd -P)
export WASI_SDK_PATH="$HERE/build/tools/wasi-sdk-24.0-arm64-macos"
export PATH="$WASI_SDK_PATH/bin:$HERE/build/tools/wasmtime-v49.0.3-aarch64-macos:$PATH"
W="$HERE/build/Python-3.14.8/cross-build/wasm32-wasip1"
A="$HERE/build/pandas-archives"; rm -rf "$A"; mkdir -p "$A"
archives=""; deps=""
for bdir in "$HERE/build/numpy-2.5.2/build-wasi" "$HERE/build/pandas-3.0.6/build-wasi"; do
  for so in $(find "$bdir" -name '*.so' | sort); do
    name=$(basename "$so" .cpython-314-wasm32-wasi.so)
    case "$name" in *_tests|_simd) continue;; esac
    pkg=$(basename "$(dirname "$bdir")" | cut -d- -f1)
    cp "$so" "$A/${pkg}_$name.a"; archives="$archives $A/${pkg}_$name.a"
    deps="$deps $(sed "s#^\([^/]\)#$bdir/\1#" "$so.deps" | tr '\n' ' ')"
  done
done
libs=$(printf '%s\n' $deps | grep '\.a$' | sort -u | tr '\n' ' ')
cp "$HERE/cross/vfsmodule.c" "$HERE/build/Python-3.14.8/Modules/vfsmodule.c"
cp "$HERE/cross/cxa_stubs.c" "$HERE/build/Python-3.14.8/Modules/vfs_cxa_stubs.c"
cp "$HERE/cross/vfs_inittab.c" "$HERE/build/Python-3.14.8/Modules/vfs_inittab.c"
{ echo "# Generated by spike s12 scripts/04b_link_python_pandas.sh: numpy 2.5.2 + pandas 3.0.6 + the vfs verb door as builtins."
  echo "*static*"
  echo "vfs vfsmodule.c vfs_cxa_stubs.c vfs_inittab.c $archives $libs -lc++ -lc++abi -lc-printscan-long-double"
  echo "zlib zlibmodule.c -I$HERE/build/zlib-wasi/include $HERE/build/zlib-wasi/lib/libz.a"; } > "$W/Modules/Setup.local"
cp "$W/Modules/Setup.local" "$HERE/cross/Setup.local.pandas.generated"
cd "$W"; make -j10 all > "$HERE/outputs/20_make_pandas.log" 2>&1 || { echo "make failed"; grep -n "error\|undefined" "$HERE/outputs/20_make_pandas.log" | head -40; exit 1; }
grep -c 'signature mismatch' "$HERE/outputs/20_make_pandas.log" || true
cp python.wasm "$HERE/build/python-pandas.wasm"; ls -la "$HERE/build/python-pandas.wasm"; shasum -a 256 "$HERE/build/python-pandas.wasm"
