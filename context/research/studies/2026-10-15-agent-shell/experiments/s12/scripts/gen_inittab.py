"""Generate cross/vfs_inittab.c: a constructor that registers every cross-built extension module on the inittab
under its dotted import name (derived from the archive's path under the meson build dir).

    python scripts/gen_inittab.py build/numpy-2.5.2/build-wasi build/pandas-3.0.6/build-wasi > cross/vfs_inittab.c
Test-only numpy modules (*_tests, _simd) are skipped.
"""
import sys
from pathlib import Path

SUFFIX = ".cpython-314-wasm32-wasi.so"
entries = []
for build_dir in sys.argv[1:]:
    root = Path(build_dir)
    for so in sorted(root.rglob("*" + SUFFIX)):
        rel = so.relative_to(root)
        name = so.name[: -len(SUFFIX)]
        if name.endswith("_tests") or name == "_simd":
            continue
        parts = list(rel.parent.parts)
        if name == "_cyutility" and not parts:
            parts = ["pandas", "_libs"]   # Cython 3.1+ shared utility module: built at the root, installed under pandas/_libs
        dotted = ".".join(parts + [name])
        entries.append((dotted, name))
print("/* Generated by scripts/gen_inittab.py (spike s12). Do not edit. */")
print("#include <Python.h>")
for dotted, name in entries:
    print(f"extern PyObject *PyInit_{name}(void);")
print("__attribute__((constructor)) static void vfs_register_builtins(void) {")
for dotted, name in entries:
    print(f'    PyImport_AppendInittab("{dotted}", PyInit_{name});')
print("}")
print(f"/* {len(entries)} modules */", file=sys.stderr)
