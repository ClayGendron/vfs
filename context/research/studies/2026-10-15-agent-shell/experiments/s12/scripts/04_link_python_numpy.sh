#!/bin/bash
# Step 3b: link numpy's archives and the `vfs` module into python.wasm as builtins through Modules/Setup.local, then `make`.
# Inputs: build/numpy-2.5.2/build-wasi/**/*.so (each is an `ar` archive the wasi-cc wrapper wrote) and their .deps files.
# makesetup only recognizes *.a as libraries, so the archives are copied under build/numpy-archives/<module>.a.
set -euo pipefail
HERE=$(CDPATH= cd "$(dirname "$0")/.." && pwd -P)
export WASI_SDK_PATH="$HERE/build/tools/wasi-sdk-24.0-arm64-macos"
export PATH="$WASI_SDK_PATH/bin:$HERE/build/tools/wasmtime-v49.0.3-aarch64-macos:$PATH"
B="$HERE/build/numpy-2.5.2/build-wasi"
A="$HERE/build/numpy-archives"
W="$HERE/build/Python-3.14.8/cross-build/wasm32-wasip1"
SETUP="$W/Modules/Setup.local"   # configure copied the source-tree Setup.local here; makesetup reads this copy
rm -rf "$A"; mkdir -p "$A"
# makesetup prefixes bare source names with $(srcdir)/Modules/ and mangles absolute ones, so the two C files are copied in.
cp "$HERE/cross/vfsmodule.c" "$HERE/build/Python-3.14.8/Modules/vfsmodule.c"
cp "$HERE/cross/cxa_stubs.c" "$HERE/build/Python-3.14.8/Modules/vfs_cxa_stubs.c"
archives=""; deps=""
for so in $(find "$B/numpy" -name '*.so' | sort); do
  name=$(basename "$so" .cpython-314-wasm32-wasi.so)
  case "$name" in *_tests|_simd) continue;; esac   # test-only modules stay out (install_tag: tests)
  cp "$so" "$A/$name.a"
  archives="$archives $A/$name.a"
  deps="$deps $(tr '\n' ' ' < "$so.deps")"
done
# .deps hold the static libs each module links with (npymath, npyrandom, mtargets, unique_hash); dedupe, keep only *.a.
libs=$(printf '%s\n' $deps | grep '\.a$' | sort -u | sed "s#^#$B/#" | tr '\n' ' ')
{
  echo "# Generated by spike s12 scripts/04_link_python_numpy.sh: numpy 2.5.2 and the vfs verb door as builtins."
  echo "*static*"
  echo "vfs vfsmodule.c vfs_cxa_stubs.c -DVFS_WITH_NUMPY $archives $libs -lc++ -lc++abi -lc-printscan-long-double"
} > "$SETUP"
cp "$SETUP" "$HERE/cross/Setup.local.generated"
cat "$SETUP" | tr ' ' '\n' | sed "s#$HERE/##" | head -60
cd "$W"
make -j10 all > "$HERE/outputs/06_make.log" 2>&1 || { echo "make failed"; grep -n "error\|undefined" "$HERE/outputs/06_make.log" | head -40; exit 1; }
grep -n "python.wasm\|vfsmodule" "$HERE/outputs/06_make.log" | cut -c1-200 | head -8
ls -la python.wasm; shasum -a 256 python.wasm
